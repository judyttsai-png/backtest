#!/usr/bin/env bash
# BACKTEST — one-time setup for macOS / Linux.
# Creates the Python virtualenv, installs backend + frontend deps, writes .env.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

echo "──────────────────────────────────────────────"
echo " BACKTEST installer (macOS / Linux)"
echo "──────────────────────────────────────────────"

# 1. Find a compatible Python. The pinned numpy/pandas/scipy have NO wheels for
#    Python 3.14 yet, so we require 3.10–3.13 (3.13 preferred).
PYTHON=""
for cand in python3.13 python3.12 python3.11 python3.10; do
  if command -v "$cand" >/dev/null 2>&1; then PYTHON="$cand"; break; fi
done
if [ -z "$PYTHON" ] && command -v python3 >/dev/null 2>&1; then
  v="$(python3 -c 'import sys;print("%d.%d"%sys.version_info[:2])' 2>/dev/null || echo "")"
  case "$v" in 3.10|3.11|3.12|3.13) PYTHON=python3 ;; esac
fi
if [ -z "$PYTHON" ]; then
  echo "ERROR: need Python 3.10–3.13 and none was found."
  echo "  Install Python 3.13 from https://www.python.org/downloads/  (or your company software center)."
  echo "  NOTE: Python 3.14 will NOT work — the pinned numpy/pandas/scipy have no 3.14 wheels."
  exit 1
fi
echo "→ Using $PYTHON ($($PYTHON --version 2>&1))"

# 2. Node check
if ! command -v node >/dev/null 2>&1; then
  echo "ERROR: Node.js not found. Install Node 18+ from https://nodejs.org/ (LTS)."
  exit 1
fi
echo "→ Using node $(node --version)  npm $(npm --version)"

# 3. Backend virtualenv + dependencies (fresh, to avoid a stale 3.14 venv)
echo "→ Setting up backend virtualenv…"
cd "$ROOT/backend"
rm -rf .venv
"$PYTHON" -m venv .venv
./.venv/bin/python -m pip install --upgrade pip >/dev/null
./.venv/bin/pip install -r requirements.txt

# 4. Backend .env (only if missing — never clobber an existing one)
if [ ! -f .env ]; then
  cat > .env <<EOF
# Generated by install.sh
DATABASE_URL=sqlite:///./parabola.sqlite3
CELERY_TASK_ALWAYS_EAGER=1
DEFAULT_DATA_PROVIDER=parquet
FX_PARQUET_PATH=$ROOT/data/fx_15min.parquet
CORS_ORIGINS=http://localhost:5173,http://127.0.0.1:5173
EOF
  echo "→ Wrote backend/.env"
else
  echo "→ backend/.env already exists — leaving it as is"
fi

# 5. Frontend dependencies
echo "→ Installing frontend dependencies…"
cd "$ROOT/frontend"
npm install

echo ""
echo "✅ Done. Start the app with:   ./start.sh"
echo "   then open http://localhost:5173"
