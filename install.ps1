# BACKTEST — one-time setup for Windows (PowerShell).
# Run from the project root:   powershell -ExecutionPolicy Bypass -File .\install.ps1
$ErrorActionPreference = "Stop"
$root = $PSScriptRoot

Write-Host "──────────────────────────────────────────────"
Write-Host " BACKTEST installer (Windows)"
Write-Host "──────────────────────────────────────────────"

# 1. Find a compatible Python. Pinned numpy/pandas/scipy have NO wheels for 3.14,
#    so require 3.10-3.13 (3.13 preferred). The 'py' launcher ships with python.org.
$pyCmd = $null
foreach ($v in @("3.13", "3.12", "3.11", "3.10")) {
  try { & py "-$v" --version *> $null 2>&1; if ($LASTEXITCODE -eq 0) { $pyCmd = @("py", "-$v"); break } } catch {}
}
if (-not $pyCmd) {
  try {
    $ver = & python -c "import sys;print('%d.%d'%sys.version_info[:2])" 2>$null
    if ($ver -match '^3\.(10|11|12|13)$') { $pyCmd = @("python") }
  } catch {}
}
if (-not $pyCmd) {
  Write-Error "Need Python 3.10-3.13 and none was found. Install Python 3.13 from https://www.python.org/downloads/ (tick 'Add python.exe to PATH'). NOTE: Python 3.14 will NOT work (no wheels for the pinned deps)."
  exit 1
}
Write-Host "-> Using Python: $($pyCmd -join ' ')"

# 2. Node check
if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
  Write-Error "Node.js not found. Install Node 18+ from https://nodejs.org/ (LTS)."
  exit 1
}
Write-Host "-> Using node $(node --version)  npm $(npm --version)"

# 3. Backend virtualenv + dependencies (fresh)
Write-Host "-> Setting up backend virtualenv..."
Set-Location "$root\backend"
if (Test-Path .venv) { Remove-Item -Recurse -Force .venv }
$venvArgs = @()
if ($pyCmd.Length -gt 1) { $venvArgs += $pyCmd[1..($pyCmd.Length - 1)] }
$venvArgs += @("-m", "venv", ".venv")
& $pyCmd[0] @venvArgs
& ".\.venv\Scripts\python.exe" -m pip install --upgrade pip | Out-Null
& ".\.venv\Scripts\python.exe" -m pip install -r requirements.txt

# 4. Backend .env (only if missing)
if (-not (Test-Path .env)) {
  $parq = ("$root\data\fx_15min.parquet") -replace '\\', '/'
  @"
# Generated by install.ps1
DATABASE_URL=sqlite:///./parabola.sqlite3
CELERY_TASK_ALWAYS_EAGER=1
DEFAULT_DATA_PROVIDER=parquet
FX_PARQUET_PATH=$parq
CORS_ORIGINS=http://localhost:5173,http://127.0.0.1:5173
"@ | Set-Content -Encoding ascii .env
  Write-Host "-> Wrote backend\.env"
}
else { Write-Host "-> backend\.env already exists - leaving it as is" }

# 5. Frontend dependencies
Write-Host "-> Installing frontend dependencies..."
Set-Location "$root\frontend"
npm install

Write-Host ""
Write-Host "Done. Start the app with:   powershell -ExecutionPolicy Bypass -File .\start.ps1"
Write-Host "then open http://localhost:5173"
